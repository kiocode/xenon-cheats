// ─── Player snapshot ──────────────────────────────────────────────────────────
struct Player
{
    bool  active;
    int   id;
    float x, y;             // tile units (snapshot value / 32), as the existing ESP expects
    float velX, velY;
    int   health;           // 0–10
    int   armor;            // 0–10
    int   weapon;
    int   team;
    int   freezeEnd;        // tick the freeze ends (-1/0 if none)
    bool  frozen;           // freezeEnd > current tick
    char  name[16];
    char  clan[12];
    bool  isLocal;
};

struct GameState
{
    bool   valid;
    int    localId;
    int    numPlayers;
    Player players[128];
};

// ─── Internal state ──────────────────────────────────────────────────────────
namespace detail
{
    inline void* g_pGC = nullptr;
    inline BYTE* gc()  { return static_cast<BYTE*>(g_pGC); }

    using fnIntersectLine = int(__fastcall*)(void*, Vec2, Vec2, Vec2*, Vec2*);
    using fnGetTile       = int(__fastcall*)(void*, int, int);
    using fnIsSolid       = int(__fastcall*)(void*, int, int);

    inline fnIntersectLine pIntersectLine = nullptr;
    inline fnGetTile       pGetTile       = nullptr;
    inline fnIsSolid       pIsSolid       = nullptr;

    inline bool Readable(const void* p, SIZE_T len) { return IsAnyReadable(p, len); }
}

// ─── API ─────────────────────────────────────────────────────────────────────

inline bool Init()
{
    if (detail::g_pGC) return true;
    detail::g_pGC = FindGameClient();
    return detail::g_pGC != nullptr;
}

// Resolve engine function pointers from module base + researched RVAs.
// Safe to call repeatedly; no-ops for RVAs left at 0x0.
inline void InitFunctions()
{
    const uintptr_t base = reinterpret_cast<uintptr_t>(GetModuleHandleA(nullptr));
    if (Offsets::Func::IntersectLine)
        detail::pIntersectLine = reinterpret_cast<detail::fnIntersectLine>(base + Offsets::Func::IntersectLine);
    if (Offsets::Func::GetTile)
        detail::pGetTile = reinterpret_cast<detail::fnGetTile>(base + Offsets::Func::GetTile);
    if (Offsets::Func::IsSolid)
        detail::pIsSolid = reinterpret_cast<detail::fnIsSolid>(base + Offsets::Func::IsSolid);
}

inline void* GetRawGameClient() { return detail::g_pGC; }

inline bool GetGameState(GameState& out)
{
    if (!detail::g_pGC && !Init()) { out.valid = false; return false; }

    BYTE* snap    = detail::gc() + Offsets::SNAP;
    BYTE* clients = detail::gc() + Offsets::CLIENTS;

    out.valid      = true;
    out.localId    = *reinterpret_cast<int*>(snap + Offsets::SNAP_LOCAL_ID);
    out.numPlayers = *reinterpret_cast<int*>(snap + Offsets::SNAP_NUM_PLAYERS);

    BYTE* chars = snap + Offsets::SNAP_CHARACTERS;

    for (int i = 0; i < 128; ++i)
    {
        BYTE*   ci = chars   + i * Offsets::CHARINFO_STRIDE;
        BYTE*   cd = clients + i * Offsets::CLIENTDATA_STRIDE;
        Player& p  = out.players[i];

        p.id      = i;
        p.isLocal = (i == out.localId);
        p.active  = *reinterpret_cast<bool*>(ci + Offsets::CHARINFO_ACTIVE);

        memcpy(p.name, cd + Offsets::CLIENTDATA_NAME, sizeof(p.name));
        memcpy(p.clan, cd + Offsets::CLIENTDATA_CLAN, sizeof(p.clan));
        p.team      = *reinterpret_cast<int*>(cd + Offsets::CLIENTDATA_TEAM);
        p.freezeEnd = Offsets::CLIENTDATA_FREEZE_END
                        ? *reinterpret_cast<int*>(cd + Offsets::CLIENTDATA_FREEZE_END) : 0;

        if (p.active)
        {
            auto* cur = reinterpret_cast<NetCharacter*>(ci + Offsets::CHARINFO_CUR);
            p.x      = cur->x    / 32.f;
            p.y      = cur->y    / 32.f;
            p.velX   = cur->velX / 256.f;
            p.velY   = cur->velY / 256.f;
            p.health = cur->health;
            p.armor  = cur->armor;
            p.weapon = cur->weapon;
            p.frozen = (p.freezeEnd > cur->tick);
        }
        else
        {
            p.x = p.y = p.velX = p.velY = 0.f;
            p.health = p.armor = p.weapon = 0;
            p.frozen = false;
        }
    }

    return true;
}

// ─── Extended reads (each no-ops until its offset is set) ─────────────────────

// Live pointer to the collision subobject, or nullptr if unavailable.
inline Collision* GetCollision()
{
    if (!detail::g_pGC || !Offsets::COLLISION) return nullptr;
    auto* c = reinterpret_cast<Collision*>(detail::gc() + Offsets::COLLISION);
    if (!detail::Readable(c, sizeof(Collision))) return nullptr;
    if (c->width <= 0 || c->height <= 0 || !detail::Readable(c->pTiles, sizeof(Tile))) return nullptr;
    return c;
}

// Tile index at integer tile coordinates (0 = AIR / out of bounds).
inline unsigned char TileAt(const Collision* c, int tileX, int tileY)
{
    if (!c || tileX < 0 || tileY < 0 || tileX >= c->width || tileY >= c->height) return 0;
    return c->pTiles[tileY * c->width + tileX].index;
}

// Tile index at a native world-pixel position.
inline unsigned char TileAtWorld(const Collision* c, float worldPxX, float worldPxY)
{
    return TileAt(c, static_cast<int>(worldPxX) / 32, static_cast<int>(worldPxY) / 32);
}

inline bool GetTuning(TuningParams& out)
{
    if (!detail::g_pGC || !Offsets::TUNING) return false;
    auto* t = reinterpret_cast<TuningParams*>(detail::gc() + Offsets::TUNING);
    if (!detail::Readable(t, sizeof(TuningParams))) return false;
    out = *t;
    return true;
}

inline bool GetLocalInput(NetPlayerInput& out)
{
    if (!detail::g_pGC || !Offsets::CONTROLS || !Offsets::CONTROLS_INPUT) return false;
    BYTE* controls = detail::gc() + Offsets::CONTROLS;
    auto* in = reinterpret_cast<NetPlayerInput*>(controls + Offsets::CONTROLS_INPUT);
    if (!detail::Readable(in, sizeof(NetPlayerInput))) return false;
    out = *in;
    return true;
}

// Per-client world position array (native pixels), if RENDER_POS/CLIENT_STRIDE set.
inline bool GetClientPos(int id, float& pxX, float& pxY)
{
    if (!detail::g_pGC || !Offsets::RENDER_POS || !Offsets::CLIENT_STRIDE) return false;
    if (id < 0 || id >= 128) return false;
    auto* v = reinterpret_cast<Vec2*>(detail::gc() + Offsets::RENDER_POS + id * Offsets::CLIENT_STRIDE);
    if (!detail::Readable(v, sizeof(Vec2))) return false;
    pxX = v->x; pxY = v->y;
    return true;
}

// ─── Engine function wrappers (call InitFunctions() once after Init()) ────────
// Coordinates are NATIVE WORLD PIXELS here (NOT the /32 tile units in Player).

// Raycast against solid geometry. Returns true on hit; outHit = collision point.
inline bool RaycastSolid(Vec2 fromPx, Vec2 toPx, Vec2& outHit)
{
    Collision* c = GetCollision();
    if (!c || !detail::pIntersectLine) return false;
    Vec2 outBefore{};
    return detail::pIntersectLine(c, fromPx, toPx, &outHit, &outBefore) != 0;
}

// Solid test at integer tile coordinates (engine authority).
inline bool IsSolidTile(int tileX, int tileY)
{
    Collision* c = GetCollision();
    if (!c || !detail::pIsSolid) return false;
    return detail::pIsSolid(c, tileX, tileY) != 0;
}

// Engine tile lookup at integer tile coordinates.
inline int GetTileEngine(int tileX, int tileY)
{
    Collision* c = GetCollision();
    if (!c || !detail::pGetTile) return 0;
    return detail::pGetTile(c, tileX, tileY);
}

