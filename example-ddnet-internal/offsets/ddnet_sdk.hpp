// ─── Network object types ─────────────────────────────────────────────────────
#pragma pack(push, 4)

struct NetCharacterCore     // 60 bytes
{
    int tick;
    int x, y;               // native world pixels (1 tile = 32 px)
    int velX, velY;         // fixed-point: world_vel = value / 256.0f
    int angle;
    int direction;          // -1, 0, 1
    int jumped;
    int hookedPlayer;
    int hookState;
    int hookTick;
    int hookX, hookY;
    int hookDx, hookDy;
};

struct NetCharacter : NetCharacterCore  // 88 bytes
{
    int playerFlags;
    int health;             // 0–10
    int armor;              // 0–10
    int ammoCount;
    int weapon;             // 0=hammer 1=gun 2=sg 3=gren 4=laser 5=ninja
    int emote;
    int attackTick;
};

struct NetPlayerInput        // 40 bytes — matches CNetObj_PlayerInput
{
    int direction;
    int targetX, targetY;
    int jump, fire, hook;
    int playerFlags;
    int wantedWeapon, nextWeapon, prevWeapon;
};

#pragma pack(pop)

static_assert(sizeof(NetCharacterCore) == 60, "NetCharacterCore layout mismatch");
static_assert(sizeof(NetCharacter)     == 88, "NetCharacter layout mismatch");
static_assert(sizeof(NetPlayerInput)   == 40, "NetPlayerInput layout mismatch");

